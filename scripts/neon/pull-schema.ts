/**
 * Regenerates the Drizzle schema (src/lib/db/schema.ts and relations.ts) from
 * the Neon branch in .env.local. The SQL migrations own the schema; this file
 * only gives queries their types, like `npm run db:types` does for Supabase.
 *
 *   npm run db:schema
 *
 * Run it after loading a branch or applying a migration. It pulls with
 * drizzle-kit into a temporary folder, then fixes what drizzle-kit gets wrong
 * for this database (see FIXES), and stops if one of them no longer matches,
 * so a drizzle-kit update can't change the output without anyone noticing.
 */
import { spawnSync } from 'node:child_process'
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

const ROOT = join(import.meta.dirname, '..', '..')
const OUT_DIR = join(ROOT, 'src', 'lib', 'db')

const HEADER = `// Generated by \`npm run db:schema\` (scripts/neon/pull-schema.ts) from the
// database. Don't edit: change the SQL migration, then regenerate. Only for
// query types: the database is the source of truth, and its exclusion
// constraints show up here as plain gist indexes.
`

interface Fix {
  file: 'schema.ts' | 'relations.ts'
  reason: string
  apply: (source: string) => string
}

const FIXES: Fix[] = [
  {
    file: 'schema.ts',
    reason: 'SQL function defaults come out as string literals',
    apply: (source) => source.replaceAll(/\.default\("([a-z_]+\.[a-z_]+\(\))"\)/g, '.default(sql`$1`)'),
  },
  {
    file: 'schema.ts',
    reason:
      'every amount reads as a number, as it did from Supabase (pull only does it for columns with a number default)',
    apply: (source) =>
      source
        .replaceAll(/numeric\(\{ precision/g, "numeric({ mode: 'number', precision")
        .replaceAll(/numeric\(("[a-z_]+"), \{ precision/g, "numeric($1, { mode: 'number', precision"),
  },
  {
    file: 'schema.ts',
    reason: "views don't report array dimensions, so pull guesses two",
    apply: (source) => source.replaceAll('.array().array("[][]")', '.array()'),
  },
  {
    file: 'schema.ts',
    reason: 'the formatter sorts drizzle-orm first, and would put that import above the header',
    apply: (source) => {
      const sqlImport = 'import { sql } from "drizzle-orm"\n'
      if (!source.includes(sqlImport)) {
        return source
      }
      return sqlImport + source.replace(sqlImport, '')
    },
  },
  {
    file: 'schema.ts',
    reason: 'profiles references auth.users, outside the pulled public schema',
    apply: (source) =>
      source
        .replace('import { pgTable,', 'import { pgSchema, pgTable,')
        .replace(
          '\n\nexport const appRole',
          '\n\n// Supabase\'s accounts table (scripts/neon/supabase-compat.sql), until Better Auth.\nconst users = pgSchema("auth").table("users", { id: uuid().primaryKey() })\n\nexport const appRole',
        ),
  },
  {
    file: 'relations.ts',
    reason: 'profiles gets a relation to auth.users, which the schema keeps private',
    apply: (source) => source.replace(/\n\s*usersInAuth: r\.one\.usersInAuth\(\{[^}]*\}\),/, ''),
  },
]

if (existsSync(join(ROOT, '.env.local'))) {
  process.loadEnvFile(join(ROOT, '.env.local'))
}

const url = process.env.DATABASE_URL_UNPOOLED
if (!url) {
  throw new Error('DATABASE_URL_UNPOOLED must be set (.env.local, from `neon checkout <branch>`)')
}

const pullDir = mkdtempSync(join(tmpdir(), 'vecora-pull-'))
try {
  const pull = spawnSync(
    process.execPath,
    [
      join(ROOT, 'node_modules', 'drizzle-kit', 'bin.cjs'),
      'pull',
      '--dialect=postgresql',
      `--url=${url}`,
      `--out=${pullDir}`,
      '--schemaFilter=public',
      '--introspect-casing=camel',
    ],
    { cwd: ROOT, encoding: 'utf8' },
  )
  if (pull.status !== 0) {
    throw new Error(`drizzle-kit pull failed:\n${pull.stdout}\n${pull.stderr}`)
  }

  for (const file of ['schema.ts', 'relations.ts'] as const) {
    let source = readFileSync(join(pullDir, file), 'utf8')
    for (const fix of FIXES) {
      if (fix.file !== file) {
        continue
      }
      const fixed = fix.apply(source)
      if (fixed === source) {
        throw new Error(
          `Nothing to fix any more in ${file}: ${fix.reason}. Check the drizzle-kit output and update FIXES.`,
        )
      }
      source = fixed
    }
    writeFileSync(join(OUT_DIR, file), HEADER + source)
  }
  console.log('Wrote src/lib/db/schema.ts and src/lib/db/relations.ts')
} finally {
  rmSync(pullDir, { recursive: true, force: true })
}
